package com.mindbase.pay.config;

import org.springframework.boot.context.properties.ConfigurationProperties;

/**
 * pay.* configuration binding. The single configuration entry point is application.yaml (+ docker/test profile variants);
 * sensitive values reference .env via ${VAR:default} placeholders.
 */
@ConfigurationProperties(prefix = "pay")
public record PayProperties(Rdbms rdbms, Mock mock, Order order, Alipay alipay, Test test,
                            Apptask apptask, Job job, Internal internal, Refund refund) {

    public record Rdbms(String url, String username, String password) {
    }

    public record Mock(boolean enabled) {
    }

    /**
     * @param maxOpenPerUser maximum unpaid orders per user (validated before placing an order, 429 when exceeded), preventing order-spam database hoarding
     */
    public record Order(int timeoutMinutes, int maxOpenPerUser) {
    }

    /**
     * Alipay face-to-face payment (M2). When enabled=true, keys are validated at startup and a missing key refuses startup.
     * Key naming aligns with the Alipay console to eliminate "which public key" ambiguity (both start with MII and are easily confused):
     * app-private-key = application private key (generated by the merchant key tool, signs requests);
     * platform-public-key = Alipay public key (provided by the platform console under "interface signing method", verifies platform response/callback signatures
     * -- not the application public key you generated yourself; filling in the wrong one makes the SDK report "the configured Alipay public key is an application public key").
     * notify-url left blank = do not rely on asynchronous callbacks, primarily query via ChannelQueryJob (a realistic choice when locally there is no public network).
     * connect/read-timeout-ms = outbound timeouts of the Alipay SDK's built-in HTTP client (the SDK does not use RestClient,
     * so the global spring.http.client.* has no effect on it); they must be set explicitly to prevent a slow channel from tying up request threads.
     */
    public record Alipay(boolean enabled, String gatewayUrl, String appId,
                         String appPrivateKey, String platformPublicKey, String notifyUrl,
                         int connectTimeoutMs, int readTimeoutMs) {
    }

    /**
     * Local test entry (/test/pay/*): disabled by default; when enabled, a matching token is still required.
     * When require-token=true, the token must not be blank (startup self-check refuses), preventing "unconfigured means open" from degrading to no authentication.
     * Structural isolation: APISIX does not route /test/*, and the app-pay port is bound to loopback only, unreachable from the public network.
     * In production, enabled must be false.
     */
    public record Test(boolean enabled, String token, boolean requireToken) {
    }

    /**
     * Timeout delegation registration (plan/1.0.8): after the order transaction commits, register an exact timer delegation with app-task.
     * When register-enabled=false or registration fails, fallback polling (jittered backoff) takes over, ensuring eventual consistency.
     */
    public record Apptask(String baseUrl, String consumerKey, boolean registerEnabled,
                          String executorBaseUrl) {
    }

    /**
     * Concurrency control parameters for fallback jobs and the executor. workers is anchored to the DB connection pool (Hikari 10 -> 8).
     *
     * @param schedulerPoolSize  scheduler thread pool size (&gt;1, so a slow job does not block the other jobs)
     * @param leaseTtlSeconds    multi-instance job lease TTL (cross-instance mutual exclusion, preventing duplicate outbound calls/duplicate processing)
     * @param reconBaseSeconds   reconciliation job base interval (cap==base means no backoff)
     * @param reconWindowHours   reconciliation look-back window (hours)
     */
    public record Job(int executorWorkers, int executorQueueCapacity,
                      int timeoutBaseSeconds, int timeoutCapSeconds,
                      int deliveryBaseSeconds, int deliveryCapSeconds,
                      int queryBaseSeconds, int schedulerPoolSize, int leaseTtlSeconds,
                      int reconBaseSeconds, int reconWindowHours) {
    }

    /**
     * Minimal authentication for internal endpoints: the executor callback token (&gt; blank then the query parameter token is
     * enforced; the token is issued via the registered executor_url query string, so app-task can POST as-is without modification).
     */
    public record Internal(String executorToken) {
    }

    /**
     * Refund reversal (M4): enabled controls the refund endpoint; maxDaysBack limits the refundable window (preventing indefinite look-back).
     */
    public record Refund(boolean enabled, int maxDaysBack) {
    }
}
