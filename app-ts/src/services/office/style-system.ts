import type { DocTemplate } from "./templates.js";

/**
 * Word Style System: one source of truth for every paragraph/character style
 * used by the renderer. All sizes/colors/spacing come from the template spec —
 * the renderer never sets typography inline except where OOXML requires it
 * (table cell runs, drawing sizes).
 *
 * Styles are named exactly as in OOXML's built-in set where possible
 * (Title/Heading 1-3/Normal/Caption) so Word shows them in the styles gallery and
 * a user template can override them by name.
 */

const W_NS = "http://schemas.openxmlformats.org/wordprocessingml/2006/main";
const XML_DECL = '<?xml version="1.0" encoding="UTF-8" standalone="yes"?>';

export interface StyleSpec {
  id: string;
  name: string;
  basedOn?: string;
  next?: string;
  qFormat?: boolean;
  /** Extra pPr fragments (spacing/indent/borders/keepNext/numPr...). */
  pPr?: string;
  /** Extra rPr fragments (fonts/color/size/bold). */
  rPr?: string;
}

export function halfPoints(pt: number): number {
  return Math.max(2, Math.round(pt * 2));
}

function spacing(theme: DocTemplate, opts: { beforePt?: number; afterPt?: number; line?: boolean } = {}): string {
  const typo = theme.typography;
  const before = opts.beforePt !== undefined ? ' w:before="' + Math.round(opts.beforePt * 20) + '"' : "";
  const after =
    ' w:after="' + Math.round((opts.afterPt ?? typo.paragraphAfterPt) * 20) + '"';
  if (typo.lineRule === "exact") {
    return "<w:spacing" + before + after + ' w:line="' + typo.lineTwips + '" w:lineRule="exact"/>';
  }
  return "<w:spacing" + before + after + ' w:line="' + typo.lineTwips + '" w:lineRule="auto"/>';
}

function indent(theme: DocTemplate): string {
  return theme.typography.indentChars > 0
    ? '<w:ind w:firstLineChars="' + theme.typography.indentChars + '"/>'
    : "";
}

function fonts(theme: DocTemplate, eastAsia: string, ascii?: string): string {
  const east = eastAsia || theme.typography.bodyFontEastAsia;
  const latin = ascii ?? theme.typography.bodyFontAscii;
  return (
    '<w:rFonts w:ascii="' + latin + '" w:hAnsi="' + latin + '" w:eastAsia="' + east + '" w:cs="' + latin + '"/>'
  );
}

function sizeRPr(half: number, color?: string, bold?: boolean): string {
  return (
    (bold ? "<w:b/>" : "") +
    (color ? '<w:color w:val="' + color + '"/>' : "") +
    '<w:sz w:val="' + half + '"/><w:szCs w:val="' + half + '"/>'
  );
}

function style(spec: StyleSpec): string {
  return (
    '<w:style w:type="paragraph" w:styleId="' + spec.id + '">' +
    '<w:name w:val="' + spec.name + '"/>' +
    (spec.basedOn ? '<w:basedOn w:val="' + spec.basedOn + '"/>' : "") +
    (spec.next ? '<w:next w:val="' + spec.next + '"/>' : "") +
    (spec.qFormat ? "<w:qFormat/>" : "") +
    (spec.pPr ? "<w:pPr>" + spec.pPr + "</w:pPr>" : "") +
    (spec.rPr ? "<w:rPr>" + spec.rPr + "</w:rPr>" : "") +
    "</w:style>"
  );
}

