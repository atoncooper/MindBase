/**
 * Numbering definitions:
 *  - numId 1 bullet / numId 2 decimal (body lists);
 *  - numId 10 multilevel heading list driven by the template (一、/（一）/1. or
 *    1 / 1.1 / 1.1.1). Heading styles reference it via numPr.
 */
export function buildNumberingXml(theme: DocTemplate): string {
  const cn = theme.numbering.style === "chapter-cn";
  const lvl = (ilvl: number, fmt: string, text: string): string =>
    '<w:lvl w:ilvl="' + ilvl + '"><w:start w:val="1"/><w:numFmt w:val="' + fmt + '"/>' +
    '<w:lvlText w:val="' + text + '"/><w:lvlJc w:val="left"/>' +
    '<w:suff w:val="' + (cn ? "nothing" : "space") + '"/>' +
    '<w:pPr><w:ind w:left="' + (ilvl === 0 ? 0 : 420) + '" w:firstLineChars="0" w:firstLine="0"/></w:pPr>' +
    (ilvl === 0 ? '<w:rPr><w:b/><w:sz w:val="' + halfPoints(theme.typography.headingSizesPt.h1) + '"/></w:rPr>' : "") +
    "</w:lvl>";
  const headingAbstract = cn
    ? '<w:abstractNum w:abstractNumId="10"><w:multiLevelType w:val="multilevel"/>' +
      lvl(0, "chineseCounting", "%1、") + lvl(1, "chineseCounting", "（%2）") + lvl(2, "decimal", "%3.") +
      "</w:abstractNum>"
    : '<w:abstractNum w:abstractNumId="10"><w:multiLevelType w:val="multilevel"/>' +
      lvl(0, "decimal", "%1.") + lvl(1, "decimal", "%1.%2") + lvl(2, "decimal", "%1.%2.%3") +
      "</w:abstractNum>";
  const headingNum = '<w:num w:numId="10"><w:abstractNumId w:val="10"/></w:num>';
  return (
    XML_DECL +
    '<w:numbering xmlns:w="' + W_NS + '">' +
    headingAbstract +
    '<w:abstractNum w:abstractNumId="0"><w:nsid w:val="1A2B3C4D"/><w:multiLevelType w:val="singleLevel"/>' +
    '<w:lvl w:ilvl="0"><w:start w:val="1"/><w:numFmt w:val="bullet"/><w:lvlText w:val="•"/><w:lvlJc w:val="left"/>' +
    '<w:pPr><w:ind w:left="440" w:hanging="220"/></w:pPr><w:rPr><w:rFonts w:ascii="Arial" w:hAnsi="Arial"/></w:rPr></w:lvl>' +
    "</w:abstractNum>" +
    '<w:abstractNum w:abstractNumId="1"><w:nsid w:val="2B3C4D5E"/><w:multiLevelType w:val="singleLevel"/>' +
    '<w:lvl w:ilvl="0"><w:start w:val="1"/><w:numFmt w:val="decimal"/><w:lvlText w:val="%1."/><w:lvlJc w:val="left"/>' +
    '<w:pPr><w:ind w:left="440" w:hanging="220"/></w:pPr></w:lvl>' +
    "</w:abstractNum>" +
    '<w:num w:numId="1"><w:abstractNumId w:val="0"/></w:num>' +
    '<w:num w:numId="2"><w:abstractNumId w:val="1"/></w:num>' +
    headingNum +
    "</w:numbering>"
  );
}
