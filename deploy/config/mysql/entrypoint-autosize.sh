#!/bin/sh
# =============================================================================
# MySQL 8.4 — container entrypoint: derive capacity from cgroup maxMem / CPU
# =============================================================================
# 生产标准：不写死 buffer pool/连接数，按容器内存上限与 CPU 核数推导，写
# /etc/mysql/conf.d/99-auto-sizing.cnf（覆盖 base 的任何容量默认），再交给官方
# docker-entrypoint.sh（init、初始化 SQL、gosu 降权、exec mysqld）。
#
# 公式（专用 DB 容器；上限可被环境变量覆盖）：
#   innodb_buffer_pool_size = mem × 50% (<2G) / 60% (<8G) / 70% (>=8G)，至少留 256MB
#   innodb_redo_log_capacity = buffer / 4（128M..4G）
#   innodb_buffer_pool_instances = 1（buffer<1G）或 min(8, buffer/1G)
#   max_connections = cpu × 100（100..500）
#   innodb_io_capacity = cpu × 500（400..8000），max = 2×
# 覆盖示例：MYSQL_BUFFER_POOL_MB=4096 MYSQL_MAX_CONNECTIONS=300
#            MYSQL_AUTOSIZE_DISABLE=1
# =============================================================================
set -eu

mem_limit_mb() {
  # cgroup v2
  if [ -r /sys/fs/cgroup/memory.max ]; then
    v=$(cat /sys/fs/cgroup/memory.max 2>/dev/null)
    if [ "$v" != "max" ] && [ -n "$v" ] && [ "$v" -gt 0 ] 2>/dev/null; then
      echo $((v / 1024 / 1024)); return
    fi
  fi
  # cgroup v1
  if [ -r /sys/fs/cgroup/memory/memory.limit_in_bytes ]; then
    v=$(cat /sys/fs/cgroup/memory/memory.limit_in_bytes 2>/dev/null)
    if [ -n "$v" ] && [ "$v" -gt 0 ] 2>/dev/null && [ "$v" -lt 9223372036854771712 ] 2>/dev/null; then
      echo $((v / 1024 / 1024)); return
    fi
  fi
  # no limit: use host MemTotal
  awk '/MemTotal:/ {print int($2/1024)}' /proc/meminfo
}
cpu_limit() {
  # cgroup v2: "<quota> <period>" or "max <period>"
  if [ -r /sys/fs/cgroup/cpu.max ]; then
    set -- $(cat /sys/fs/cgroup/cpu.max 2>/dev/null)
    q=$1; p=${2:-100000}
    if [ "$q" != "max" ] && [ -n "$q" ] && [ "$q" -gt 0 ] 2>/dev/null; then
      echo $(( (q + p - 1) / p )); return
    fi
  fi
  # cgroup v1
  if [ -r /sys/fs/cgroup/cpu/cpu.cfs_quota_us ] && [ -r /sys/fs/cgroup/cpu/cpu.cfs_period_us ]; then
    q=$(cat /sys/fs/cgroup/cpu/cpu.cfs_quota_us 2>/dev/null)
    p=$(cat /sys/fs/cgroup/cpu/cpu.cfs_period_us 2>/dev/null)
    if [ -n "$q" ] && [ "$q" -gt 0 ] 2>/dev/null && [ -n "$p" ] && [ "$p" -gt 0 ] 2>/dev/null; then
      echo $(( (q + p - 1) / p )); return
    fi
  fi
  n=$(awk '/^processor/ {n++} END {print (n ? n : 1)}' /proc/cpuinfo)
  echo "$n"
}
clamp() { v=$1; lo=$2; hi=$3; [ "$v" -lt "$lo" ] && v=$lo; [ "$v" -gt "$hi" ] && v=$hi; echo "$v"; }

MEM_MB=$(mem_limit_mb)
CPU=$(cpu_limit)
[ -n "$MEM_MB" ] 2>/dev/null || MEM_MB=1024
[ "$MEM_MB" -lt 256 ] 2>/dev/null && MEM_MB=256
CPU=$(clamp "$CPU" 1 64)

if [ "${MYSQL_AUTOSIZE_DISABLE:-0}" = "1" ]; then
  echo "[mysqld-autosize] disabled (MYSQL_AUTOSIZE_DISABLE=1)" >&2
else
  if [ "$MEM_MB" -lt 2048 ]; then ratio=50
  elif [ "$MEM_MB" -lt 8192 ]; then ratio=60
  else ratio=70
  fi
  BP=$(( MEM_MB * ratio / 100 ))
  [ "$BP" -lt 128 ] && BP=128
  # 至少给连接/临时内存留 256MB
  [ "$BP" -gt $(( MEM_MB - 256 )) ] && BP=$(( MEM_MB - 256 ))
  [ "$BP" -lt 128 ] && BP=128
  [ -n "${MYSQL_BUFFER_POOL_MB:-}" ] && BP="${MYSQL_BUFFER_POOL_MB}"

  REDO=$(( BP / 4 ))
  REDO=$(clamp "$REDO" 128 4096)

  if [ "$BP" -ge 1024 ]; then
    INST=$(( BP / 1024 ))
    INST=$(clamp "$INST" 1 8)
  else
    INST=1
  fi

  CONN=$(( CPU * 100 ))
  CONN=$(clamp "$CONN" 100 500)
  [ -n "${MYSQL_MAX_CONNECTIONS:-}" ] && CONN="${MYSQL_MAX_CONNECTIONS}"

  IO=$(( CPU * 500 ))
  IO=$(clamp "$IO" 400 8000)
  IOMAX=$(( IO * 2 ))

  TIO=$(clamp "$CPU" 4 16)
  LOGBUF=$(( CPU * 16 )); LOGBUF=$(clamp "$LOGBUF" 16 128)
  TOCACHE=$(( CPU * 500 )); TOCACHE=$(clamp "$TOCACHE" 400 4000)
  TCACHE=$(( CPU * 8 ))
  TCACHE=$(clamp "$TCACHE" 8 64)

  cat > /etc/mysql/conf.d/99-auto-sizing.cnf <<EOF
# generated by entrypoint-autosize.sh — do not edit (source: deploy/config/mysql)
[mysqld]
innodb-buffer-pool-size          = ${BP}M
innodb-buffer-pool-instances     = ${INST}
innodb-redo-log-capacity         = ${REDO}M
innodb-io-capacity               = ${IO}
innodb-io-capacity-max           = ${IOMAX}
innodb-read-io-threads           = ${TIO}
innodb-write-io-threads          = ${TIO}
max-connections                  = ${CONN}
thread-cache-size                = ${TCACHE}
innodb-log-buffer-size           = ${LOGBUF}M
table-open-cache                 = ${TOCACHE}
table-definition-cache           = ${TOCACHE}
EOF
  echo "[mysqld-autosize] mem=${MEM_MB}MB cpu=${CPU} -> buffer=${BP}MB redo=${REDO}MB instances=${INST} max_connections=${CONN} io=${IO}" >&2
fi

# compose 只挂了 entrypoint、没写 command 时，官方 docker-entrypoint.sh 会因为
# 没有参数直接 exec 空命令并以 0 退出（容器无限重启）。默认补 mysqld。
if [ "$#" -eq 0 ]; then
  set -- mysqld
fi
exec /usr/local/bin/docker-entrypoint.sh "$@"
