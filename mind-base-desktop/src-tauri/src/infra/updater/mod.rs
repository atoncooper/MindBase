//! GitHub release update checking.
//!
//! The desktop app is offline-first: every failure path here degrades to an
//! `Err(String)` that callers may ignore silently. Network IO is blocking
//! (ureq) and therefore always wrapped in `spawn_blocking`.
//!
//! - [`types`] — payload structs exchanged with the webview.
//! - [`github`] — release metadata requests, tag/URL parsing, asset picking.
//! - [`download`] — installer download with throttled progress events.
//! - [`install`] — launching the downloaded installer.
//! - [`plugin`] — signed seamless updates via `tauri-plugin-updater`.
//! - [`commands`] — Tauri commands of the manual update flow.

mod commands;
mod download;
mod github;
mod install;
mod plugin;
mod types;

pub use commands::check_update;

// ---------------------------------------------------------------------------
// In-app installer download & launch
// ---------------------------------------------------------------------------
pub use download::download_update;
pub use install::run_update_installer;

// ---------------------------------------------------------------------------
// Signed seamless updates (tauri-plugin-updater)
// ---------------------------------------------------------------------------
pub use plugin::{updater_check, updater_install, PendingUpdate};
#[allow(unused_imports)]
pub use types::{
    GithubAsset, UpdateDownloadEvent, UpdateDownloadSummary, UpdateInfo, UpdaterInstallEvent,
    UpdaterMeta,
};

// Macros generated by `#[tauri::command]` next to each command function; the
// `generate_handler!` registry resolves them through this module path.
#[allow(unused_imports)]
pub use commands::{__cmd__check_update, __tauri_command_name_check_update};
#[allow(unused_imports)]
pub use download::{__cmd__download_update, __tauri_command_name_download_update};
#[allow(unused_imports)]
pub use install::{__cmd__run_update_installer, __tauri_command_name_run_update_installer};
#[allow(unused_imports)]
pub use plugin::{
    __cmd__updater_check, __cmd__updater_install, __tauri_command_name_updater_check,
    __tauri_command_name_updater_install,
};
