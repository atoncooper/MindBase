//! Local file ingestion: files/folders on disk → text extraction (Python
//! sidecar `scripts/doc_extract.py`) → chunk → embed → the built-in vector
//! store, mirroring `ingest.rs`'s video pipeline.
//!
//! Documents get `doc_id = "file:" + md5(abs path)` so re-ingesting the same
//! path replaces its chunks idempotently (same upsert semantics as videos);
//! the `documents` row stores `source_type = 'file'` and the absolute path.
//! Like the video pipeline, v1 is deliberately single-flight — the frontend
//! keeps the start button busy — and one bad file never blocks the rest.

mod documents;
mod extract;
mod ocr;
mod pipeline;
mod scan;
mod types;

use std::path::Path;

/// 供论文导入等场景复用：用 bundled Python 抽取一个文档的标题与正文文本。
///
/// 覆盖 doc_extract.py 支持的 txt / md / pdf / docx / html 等格式；会自动
/// ensure 所需 Python 运行时依赖（pymupdf / python-docx 按需），失败返回中文错误。
#[allow(dead_code)] // 目前由 research 导入模块调用；命令注册前暂时无引用。
pub(crate) fn extract_document_text(data_dir: &Path, file: &Path) -> Result<(String, String), String> {
    let exe = crate::infra::python_runtime::ensure_doc_extract_python(
        data_dir, true, true, false,
    )?;
    let extracted = extract::extract_text(&exe, file)?;
    Ok((extracted.title, extracted.text))
}

